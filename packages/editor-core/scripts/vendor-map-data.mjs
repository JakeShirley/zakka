// Downloads Natural Earth (public domain) vector data and writes the compact files bundled by
// the map layer into vendor/maps. Run from packages/editor-core with:
//   node scripts/vendor-map-data.mjs [--source <directory with Natural Earth .geojson files>]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { quantize } from "topojson-client";
import { topology } from "topojson-server";
import { presimplify, quantile, simplify } from "topojson-simplify";

const naturalEarthCommit = "ca96624a56bd078437bca8184e78163e5039ad19";
const naturalEarthBaseUrl = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${naturalEarthCommit}/geojson`;

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const vendorRoot = join(packageRoot, "vendor/maps");
const sourceFlagIndex = process.argv.indexOf("--source");
const sourceDirectory = sourceFlagIndex >= 0 ? process.argv[sourceFlagIndex + 1] : null;

const loadGeoJson = async (name) => {
  if (sourceDirectory) {
    return JSON.parse(readFileSync(join(sourceDirectory, `${name}.geojson`), "utf8"));
  }

  const response = await fetch(`${naturalEarthBaseUrl}/${name}.geojson`);

  if (!response.ok) {
    throw new Error(`Failed to download ${name}: ${response.status}`);
  }

  return response.json();
};

const slimFeatures = (collection, pickProperties) => ({
  type: "FeatureCollection",
  features: collection.features
    .filter((feature) => feature.geometry)
    .map((feature) => ({
      type: "Feature",
      properties: pickProperties(feature.properties),
      geometry: feature.geometry,
    })),
});

const countryProperties = (properties) => ({ id: properties.ADM0_A3, name: properties.NAME });
const noProperties = () => ({});

const buildTopology = (objects, keepFraction) => {
  let world = topology(objects);

  if (keepFraction < 1) {
    world = presimplify(world);
    world = simplify(world, quantile(world, 1 - keepFraction));
    // Drop the simplification weights so they are not serialized as a third coordinate.
    world.arcs = world.arcs.map((arc) => arc.map(([x, y]) => [x, y]));
  }

  return JSON.stringify(quantize(world, 1e5));
};

const writeVendorFile = (fileName, contents) => {
  writeFileSync(join(vendorRoot, fileName), contents);
  console.log(`${fileName}: ${(Buffer.byteLength(contents) / 1024).toFixed(0)} KB`);
};

mkdirSync(vendorRoot, { recursive: true });

writeVendorFile(
  "world-50m.topojson",
  buildTopology(
    {
      countries: slimFeatures(await loadGeoJson("ne_50m_admin_0_countries"), countryProperties),
      lakes: slimFeatures(await loadGeoJson("ne_50m_lakes"), noProperties),
      rivers: slimFeatures(await loadGeoJson("ne_50m_rivers_lake_centerlines"), noProperties),
      states: slimFeatures(
        await loadGeoJson("ne_50m_admin_1_states_provinces_lines"),
        noProperties,
      ),
    },
    1,
  ),
);

writeVendorFile(
  "world-10m.topojson",
  buildTopology(
    {
      countries: slimFeatures(await loadGeoJson("ne_10m_admin_0_countries"), countryProperties),
      lakes: slimFeatures(await loadGeoJson("ne_10m_lakes"), noProperties),
      rivers: slimFeatures(await loadGeoJson("ne_10m_rivers_lake_centerlines"), noProperties),
    },
    0.75,
  ),
);

const places = await loadGeoJson("ne_10m_populated_places_simple");
const placeRows = places.features
  .map(({ properties }) => ({
    name: properties.name,
    region: properties.adm1name ?? "",
    country: properties.adm0name ?? "",
    latitude: Math.round(properties.latitude * 1e4) / 1e4,
    longitude: Math.round(properties.longitude * 1e4) / 1e4,
    population: Math.max(0, Math.round(properties.pop_max ?? 0)),
  }))
  .filter((place) => place.name)
  .sort((left, right) => right.population - left.population);
const sanitizeCell = (value) => String(value).replaceAll(/[\t\r\n]+/g, " ");

writeVendorFile(
  "places.tsv",
  `${placeRows
    .map((place) =>
      [place.name, place.region, place.country, place.latitude, place.longitude, place.population]
        .map(sanitizeCell)
        .join("\t"),
    )
    .join("\n")}\n`,
);

writeFileSync(
  join(vendorRoot, "SOURCE.md"),
  `# Map data\n\nGenerated by \`scripts/vendor-map-data.mjs\` from [Natural Earth](https://www.naturalearthdata.com/) (public domain) at commit \`${naturalEarthCommit}\` of [nvkelso/natural-earth-vector](https://github.com/nvkelso/natural-earth-vector).\n\n- \`world-50m.topojson\`: 1:50m countries, lakes, rivers, and state/province lines.\n- \`world-10m.topojson\`: 1:10m countries, lakes, and rivers (75% of vertices kept) for zoomed-in maps.\n- \`places.tsv\`: 1:10m populated places (name, region, country, latitude, longitude, population) for place search.\n`,
);
